"""Deterministic CLI source identity; no Git, time, environment or network inputs."""
import argparse
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
GENERATED = pathlib.Path('Sources/JSONCLIEngine/CLIBuildIdentity.swift')


def rendered(root=ROOT):
    paths = [root / 'Package.swift'] + sorted((root / 'Sources').rglob('*'))
    records = []
    for path in paths:
        if not path.is_file() or path.relative_to(root) == GENERATED:
            continue
        if path.is_symlink():
            raise ValueError('Source identity cannot follow symlinks')
        records.append(hashlib.sha256(path.read_bytes()).hexdigest() + '  ' + path.relative_to(root).as_posix() + '\n')
    value = hashlib.sha256(''.join(records).encode()).hexdigest()
    return ('// SPDX-License-Identifier: Apache-2.0\n'
            '// Generated by Scripts/generate_cli_identity.py; excludes this file.\n'
            '// SHA-256 of the ordered Package.swift + Sources content manifest, not a Git commit.\n'
            'package enum CLIBuildIdentity {\n'
            '    package static let revision = "sha256:' + value + '"\n'
            '    package static let kind = "source-sha256"\n'
            '}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = rendered()
    path = ROOT / GENERATED
    if args.check:
        if not path.is_file() or path.read_text() != expected:
            print('CLI_IDENTITY failed stale generated source identity', file=sys.stderr)
            return 1
    else:
        path.write_text(expected)
    print('CLI_IDENTITY passed source_manifest=Package.swift+Sources git_required=false')
    return 0


if __name__ == '__main__':
    sys.exit(main())
